<?php

declare(strict_types=1);

namespace App\Core;

use PHPMailer\PHPMailer\Exception as PHPMailerException;
use PHPMailer\PHPMailer\PHPMailer;

/**
 * Thin wrapper around PHPMailer for SMTP email delivery.
 *
 * Dependency note: this class requires phpmailer/phpmailer (declared in
 * composer.json) to be installed via `composer install`. If the vendor
 * autoload hasn't been run (e.g. in an environment with no package-registry
 * network access), send() logs the failure and returns false instead of
 * fatal-erroring the whole request — appointment booking and other flows
 * that trigger a notification email must still complete even if the email
 * itself cannot be sent right now.
 */
final class Mailer
{
    public function __construct(
        private string $host,
        private int $port,
        private string $encryption,
        private string $username,
        private string $password,
        private string $fromAddress,
        private string $fromName
    ) {
    }

    public static function fromEnv(): self
    {
        return new self(
            (string) Env::get('MAIL_HOST', ''),
            Env::getInt('MAIL_PORT', 587),
            (string) Env::get('MAIL_ENCRYPTION', 'tls'),
            (string) Env::get('MAIL_USERNAME', ''),
            (string) Env::get('MAIL_PASSWORD', ''),
            (string) Env::get('MAIL_FROM_ADDRESS', 'no-reply@example.com'),
            (string) Env::get('MAIL_FROM_NAME', 'PhysioWeb Clinic')
        );
    }

    /**
     * @param array<int, array{content: string, name: string, mime?: string}> $attachments
     *        Raw in-memory attachments (e.g. a PDF invoice generated by PdfService),
     *        added via PHPMailer::addStringAttachment so no temp file is needed.
     */
    public function send(string $toEmail, string $toName, string $subject, string $htmlBody, string $plainBody = '', array $attachments = []): bool
    {
        if (!class_exists(PHPMailer::class)) {
            Logger::warning('Mailer::send skipped: PHPMailer is not installed (run composer install).', ['to' => $toEmail, 'subject' => $subject]);
            return false;
        }

        try {
            $mail = new PHPMailer(true);
            $mail->isSMTP();
            $mail->Host = $this->host;
            $mail->Port = $this->port;
            $mail->SMTPAuth = true;
            $mail->Username = $this->username;
            $mail->Password = $this->password;
            $mail->SMTPSecure = $this->encryption === 'ssl' ? PHPMailer::ENCRYPTION_SMTPS : PHPMailer::ENCRYPTION_STARTTLS;
            $mail->CharSet = 'UTF-8';

            $mail->setFrom($this->fromAddress, $this->fromName);
            $mail->addAddress($toEmail, $toName);
            $mail->isHTML(true);
            $mail->Subject = $subject;
            $mail->Body = $htmlBody;
            $mail->AltBody = $plainBody !== '' ? $plainBody : strip_tags($htmlBody);

            foreach ($attachments as $attachment) {
                $mail->addStringAttachment($attachment['content'], $attachment['name'], 'base64', $attachment['mime'] ?? 'application/octet-stream');
            }

            $mail->send();
            return true;
        } catch (PHPMailerException|\Throwable $e) {
            Logger::error('Mail send failed: ' . $e->getMessage(), ['to' => $toEmail, 'subject' => $subject]);
            return false;
        }
    }
}
